create index if not exists artists_search_idx on public.artists using gin (to_tsvector('simple', coalesce(name,'') || ' ' || coalesce(bio,'')));
create index if not exists songs_search_idx on public.songs using gin (to_tsvector('simple', coalesce(title,'')));
create index if not exists events_status_starts_idx on public.events(status, starts_at);
create index if not exists ticket_types_event_idx on public.ticket_types(event_id);
create index if not exists reservations_expiry_idx on public.ticket_reservations(status, expires_at);

